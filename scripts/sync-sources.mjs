// Generates src/data/sources.generated.json from the canonical sources:
//   ../cv-ats/data/cv-*.json          -> archetypes, contact (MX), work, projects
//   ../cv-ats/src/contactVariants.ts  -> contact (US)
//   ../JobSearch/perfil/job_evaluation.md §4         -> archetype scope
//   ../JobSearch/perfil/common_application_answers.md §3.1 -> verified facts
// Runs before dev/build. If the sibling repos are missing (e.g. CI), it keeps
// the committed file so the build still works.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CV_ATS = resolve(root, '../cv-ats');
const JOBSEARCH = resolve(root, '../JobSearch');
const OUT = resolve(root, 'src/data/sources.generated.json');
const CV_BASE_URL = 'https://cv-ats-eyd.pages.dev';

const ARCHETYPES = [
  { slug: 'cv-android-platform', number: 1, title: 'Android Platform & Core Architecture', pdf: 'JesusDMedinaC_Android_CV.pdf' },
  { slug: 'cv-kmp-architect', number: 2, title: 'Kotlin Multiplatform (KMP) Architect', pdf: 'JesusDMedinaC_KMP_CV.pdf' },
  { slug: 'cv-founding-mobile', number: 3, title: 'Founding Mobile & Product Engineer', pdf: 'JesusDMedinaC_Mobile_CV.pdf' }
];

const required = [
  ...ARCHETYPES.map(a => `${CV_ATS}/data/${a.slug}.json`),
  `${CV_ATS}/src/contactVariants.ts`,
  `${JOBSEARCH}/perfil/job_evaluation.md`,
  `${JOBSEARCH}/perfil/common_application_answers.md`
];
const missing = required.filter(p => !existsSync(p));
if (missing.length) {
  if (!existsSync(OUT)) {
    console.error(`[sync-sources] Missing sources and no committed ${OUT}:\n${missing.join('\n')}`);
    process.exit(1);
  }
  console.warn(`[sync-sources] Sources not found, keeping committed sources.generated.json:\n${missing.join('\n')}`);
  process.exit(0);
}

const readJson = p => JSON.parse(readFileSync(p, 'utf8'));
const cvs = Object.fromEntries(ARCHETYPES.map(a => [a.slug, readJson(`${CV_ATS}/data/${a.slug}.json`)]));
const { contactVariants } = await import(pathToFileURL(`${CV_ATS}/src/contactVariants.ts`).href);

// Archetype scope: "- `cv-xxx.json`: scope" bullets in job_evaluation.md §4
const evaluation = readFileSync(`${JOBSEARCH}/perfil/job_evaluation.md`, 'utf8');
const scopeOf = slug => {
  const m = evaluation.match(new RegExp('^- `' + slug + '\\.json`:\\s*(.+)$', 'm'));
  if (!m) throw new Error(`[sync-sources] No scope for ${slug} in job_evaluation.md §4`);
  return m[1].trim();
};

// Verified facts: bullets of common_application_answers.md §3.1
const answers = readFileSync(`${JOBSEARCH}/perfil/common_application_answers.md`, 'utf8');
const factsSection = answers.split(/^## 3\.1.*$/m)[1]?.split(/^---$/m)[0];
if (!factsSection) throw new Error('[sync-sources] §3.1 not found in common_application_answers.md');
const verifiedFacts = factsSection
  .split('\n')
  .filter(l => l.startsWith('- '))
  .map(l => l.slice(2).replace(/\*\*/g, '').replace(/`/g, '').trim());

const base = cvs['cv-android-platform'].basics;
const contact = {
  mx: {
    label: 'MX',
    phone: base.phone,
    city: base.location.city,
    region: base.location.region,
    countryCode: base.location.countryCode
  },
  us: {
    label: contactVariants.us.label,
    phone: contactVariants.us.phone,
    city: contactVariants.us.location.city,
    region: contactVariants.us.location.region,
    countryCode: contactVariants.us.location.countryCode
  }
};

// Work and projects: union across the 3 archetypes (every claim traces to a canonical CV)
const work = new Map();
const projects = new Map();
for (const a of ARCHETYPES) {
  for (const w of cvs[a.slug].work) {
    const entry = work.get(w.name) || {
      name: w.name,
      position: w.position,
      startDate: w.startDate,
      endDate: w.endDate || null,
      summary: w.summary || '',
      highlights: []
    };
    for (const h of [...(w.highlights || []), ...(w.responsibilities || [])]) {
      if (!entry.highlights.includes(h)) entry.highlights.push(h);
    }
    work.set(w.name, entry);
  }
  for (const p of cvs[a.slug].projects || []) {
    const key = p.name.startsWith('Zora') ? 'Zora Community' : p.name;
    if (!projects.has(key)) projects.set(key, { name: key, description: p.description || '' });
  }
}
const workList = [...work.values()].sort((a, b) => (b.startDate || '').localeCompare(a.startDate || ''));

const sources = {
  _note: 'Generated by scripts/sync-sources.mjs from cv-ats and JobSearch. Do not edit by hand.',
  cvBaseUrl: CV_BASE_URL,
  name: base.name,
  email: base.email,
  contact,
  archetypes: ARCHETYPES.map(a => ({
    ...a,
    label: cvs[a.slug].basics.label,
    scope: scopeOf(a.slug),
    urlMx: `${CV_BASE_URL}/${a.slug}/`,
    urlUs: `${CV_BASE_URL}/${a.slug}-us/`
  })),
  work: workList,
  projects: [...projects.values()],
  verifiedFacts
};

const next = JSON.stringify(sources, null, 2) + '\n';
const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (next !== prev) {
  writeFileSync(OUT, next);
  console.log(`[sync-sources] Updated sources.generated.json (${workList.length} roles, ${projects.size} projects, ${verifiedFacts.length} verified facts)`);
} else {
  console.log('[sync-sources] sources.generated.json already up to date');
}
